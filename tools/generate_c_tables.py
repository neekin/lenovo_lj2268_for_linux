#!/usr/bin/env python3
"""Generate native protocol constants from the unchanged Python reference."""
import argparse
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[1]


def generate():
    ref = runpy.run_path(str(ROOT / "rastertolkpl"), run_name="lhpl_tables")
    lines = ["/* Generated by tools/generate_c_tables.py; do not edit. */",
             "typedef struct { unsigned pw, ph, length; unsigned char data[59]; } paper_template;", ""]
    for name in ("SJ_PAYLOAD", "EP_PAYLOAD"):
        data = ref[name]
        assert len(data) == 58
        values = ",".join("0x%02x" % x for x in data)
        lines.append("static const unsigned char %s[58] = {%s};" % (name, values))
    lines.append("static const paper_template PAPERS[] = {")
    for (pw, ph), name in ref["PAPER_BY_PT"].items():
        data = ref["SIZE_TEMPLATES"][name][2]
        assert len(data) in (58, 59)
        values = ",".join("0x%02x" % x for x in data)
        lines.append("    {%d, %d, %d, {%s}}, /* %s */" % (pw, ph, len(data), values, name))
    lines.extend(["};", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "source/protocol_tables.h"
    text = generate()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit("C protocol tables differ from the Python reference; regenerate them.")
        print("C protocol tables match the Python reference")
    else:
        path.write_text(text)
